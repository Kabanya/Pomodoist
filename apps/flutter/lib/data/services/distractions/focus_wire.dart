import 'package:pomodoist/domain/models/focus/focus_models.dart';

DateTime _date(Map j, String key) => DateTime.parse(j[key] as String).toUtc();
DateTime? _optional(Map j, String key) => j[key] == null ? null : _date(j, key);
FocusRunItem liveRun(Map j) => FocusRunItem(
  id: j['id'],
  userId: j['userId'] ?? '',
  presetId: j['presetId'],
  status: j['status'],
  startedAt: _date(j, 'startedAt'),
  targetWorkIntervals: j['targetWorkIntervals'],
  completedWorkIntervals: j['completedWorkIntervals'],
  createdAt: _date(j, 'createdAt'),
  updatedAt: _date(j, 'updatedAt'),
  taskId: j['taskId'],
  projectId: j['projectId'],
  endedAt: _optional(j, 'endedAt'),
  note: j['note'],
);
FocusIntervalItem liveInterval(Map j) => FocusIntervalItem(
  id: j['id'],
  runId: j['runId'],
  type: j['type'],
  status: j['status'],
  plannedSeconds: j['plannedSeconds'],
  startedAt: _date(j, 'startedAt'),
  pausedTotalSeconds: j['pausedTotalSeconds'],
  sequenceNumber: j['sequenceNumber'],
  createdAt: _date(j, 'createdAt'),
  updatedAt: _date(j, 'updatedAt'),
  taskId: j['taskId'],
  projectId: j['projectId'],
  pausedAt: _optional(j, 'pausedAt'),
  completedAt: _optional(j, 'completedAt'),
  stoppedAt: _optional(j, 'stoppedAt'),
);
Map<String, dynamic> runWire(FocusRunItem r) => {
  'id': r.id,
  'userId': r.userId,
  'presetId': r.presetId,
  'status': r.status,
  'startedAt': r.startedAt.toUtc().toIso8601String(),
  'endedAt': r.endedAt?.toUtc().toIso8601String(),
  'targetWorkIntervals': r.targetWorkIntervals,
  'completedWorkIntervals': r.completedWorkIntervals,
  'createdAt': r.createdAt.toUtc().toIso8601String(),
  'updatedAt': r.updatedAt.toUtc().toIso8601String(),
  'taskId': r.taskId,
  'projectId': r.projectId,
  'note': r.note,
};
Map<String, dynamic> intervalWire(FocusIntervalItem r) => {
  'id': r.id,
  'runId': r.runId,
  'type': r.type,
  'status': r.status,
  'startedAt': r.startedAt.toUtc().toIso8601String(),
  'pausedAt': r.pausedAt?.toUtc().toIso8601String(),
  'completedAt': r.completedAt?.toUtc().toIso8601String(),
  'stoppedAt': r.stoppedAt?.toUtc().toIso8601String(),
  'plannedSeconds': r.plannedSeconds,
  'pausedTotalSeconds': r.pausedTotalSeconds,
  'sequenceNumber': r.sequenceNumber,
  'createdAt': r.createdAt.toUtc().toIso8601String(),
  'updatedAt': r.updatedAt.toUtc().toIso8601String(),
  'taskId': r.taskId,
  'projectId': r.projectId,
};
Map<String, dynamic> presetWire(FocusPresetItem p) => {
  'id': p.id,
  'name': p.name,
  'workSeconds': p.workSeconds,
  'shortBreakSeconds': p.shortBreakSeconds,
  'longBreakSeconds': p.longBreakSeconds,
  'intervalsBeforeLongBreak': p.intervalsBeforeLongBreak,
  'autoStartBreaks': p.autoStartBreaks,
  'autoStartWork': p.autoStartWork,
  'allowPause': p.allowPause,
  'strictMode': p.strictMode,
  'isDefault': p.isDefault,
};
