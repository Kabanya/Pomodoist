export function text(message, values = {}) {
  const key = keys[message];
  let result = key ? globalThis.chrome?.i18n?.getMessage(key) || message : message;
  for (const [name, value] of Object.entries(values)) result = result.replaceAll(`{${name}}`, String(value));
  return result;
}
export function localize(document) {
  document.documentElement.lang = globalThis.chrome?.i18n?.getUILanguage() || 'en';
  for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = text(element.dataset.i18n);
  for (const element of document.querySelectorAll('[placeholder],[aria-label]')) {
    for (const attribute of ['placeholder', 'aria-label']) if (element.hasAttribute(attribute)) element.setAttribute(attribute, text(element.getAttribute(attribute)));
  }
}
